import SwiftUI

/// Central color tokens for the app, derived from the mint vintage-radio icon.
extension Color {
    /// Primary brand accent — deep teal (the icon's grille/dial green), legible on white.
    static let brand = Color(hex: "#2E9E8F")
    /// Soft mint screen background.
    static let appBackground = Color(hex: "#EAF7F3")
    /// Slightly stronger mint for nav bars and raised surfaces.
    static let mintSurface = Color(hex: "#D6EFE8")
}
